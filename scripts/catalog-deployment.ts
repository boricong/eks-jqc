import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir,copyFile,constants} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {JsonStore} from '../server/src/storage.ts';
import {migrateState} from '../server/src/migration.ts';
const file='data/runtime/state.json',master='data/master/organizations.json';
const raw=await readFile(file),orgRaw=await readFile(master),before=JSON.parse(raw.toString('utf8'));
const expected=Number(process.argv[2]);
assert.ok(Number.isInteger(expected),'Pass the reviewed source revision. Stop the development server first.');
assert.equal(before.revision,expected,'Source changed: review the current data before deployment.');
assert.equal(before.schemaVersion,4,'This deployment accepts schema 4 only.');
const now=new Date().toLocaleString('sv-SE',{timeZone:'Asia/Seoul'}).replace(/[-: ]/g,'');
const stateBackup=`data/backups/state/before-catalog-deployment-${now}.json`,orgBackup=`data/backups/organizations/before-catalog-deployment-${now}.json`;
await mkdir('data/backups/state',{recursive:true});await mkdir('data/backups/organizations',{recursive:true});
await copyFile(file,stateBackup,constants.COPYFILE_EXCL);await copyFile(master,orgBackup,constants.COPYFILE_EXCL);
const hash=(bytes:Buffer)=>createHash('sha256').update(bytes).digest('hex');
assert.equal(hash(await readFile(stateBackup)),hash(raw));assert.equal(hash(await readFile(orgBackup)),hash(orgRaw));
await new JsonStore(file).migrate(migrateState);
const migrated=await readFile(file),after=JSON.parse(migrated.toString('utf8'));
const {schemaVersion,revision,catalogBatches,...afterRecords}=after;
const {schemaVersion:oldVersion,revision:oldRevision,...beforeRecords}=before;
assert.equal(schemaVersion,5);assert.equal(revision,expected+1);assert.deepEqual(catalogBatches,[]);assert.deepEqual(afterRecords,beforeRecords);
assert.equal(hash(await readFile(master)),hash(orgRaw));
await new JsonStore(file).migrate(migrateState);assert.equal(hash(await readFile(file)),hash(migrated));
const report={appliedAtKst:now,stateBackup,orgBackup,beforeRevision:expected,afterRevision:revision,beforeHash:hash(raw),afterHash:hash(migrated),organizationHash:hash(orgRaw),preservedCollections:Object.fromEntries(Object.entries(beforeRecords).filter(([,v])=>Array.isArray(v)).map(([k,v])=>[k,(v as unknown[]).length])),allOriginalRecordsEqual:true,repeatedMigrationUnchanged:true};
await writeFile('data/runtime/catalog-deployment-verification.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
